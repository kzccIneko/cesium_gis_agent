"""寒暄与元问题的快速路由。

为什么要这一层：

以前所有输入都直接丢给 LLM 规划器。于是用户说「你好」，模型会认真推理一遍，
判定它不属于地理空间分析任务，再拼一句拒答文案 —— **耗时近 20 秒，还把内部提示词
模板（"向用户说明问候语不属于…范围"）直接当成回答吐给用户**。这是很糟的体验。

寒暄、自我介绍、能力询问这类问题有三个特点：
1. 不需要调用任何工具；
2. 答案相对固定，用规则比用 4B 小模型稳定得多（小模型容易在自由闲聊里胡编）；
3. 用户正在等回复，应该**立刻**回答。

所以这一层放在 Agent 图之前，命中即直接返回，**0 次 LLM 调用**。

⚠ 边界：这一层只管"不是任务"的输入。任何带地理分析意图的句子都不能命中，
否则会破坏工具链评测（那条 97.5% 的链路不能受影响）。
"""

from __future__ import annotations

import re
from typing import Optional

# 命中即判定为寒暄/元问题
_GREETINGS = {
    "你好", "您好", "你们好", "hi", "hello", "嗨", "哈喽", "嘿", "hey",
    "早上好", "上午好", "中午好", "下午好", "晚上好",
    "在吗", "在不在", "有人吗", "有人没", "还在吗", "测试", "test", "你好呀",
}
_THANKS = {
    "谢谢", "感谢", "多谢", "谢谢啦", "辛苦了", "谢了", "thx", "thanks", "thank you",
}
_FAREWELL = {"再见", "拜拜", "bye", "走了", "下次聊", "886"}
_WHO_ARE_YOU = {
    "你是谁", "你叫什么", "你叫什么名字", "你是干嘛的", "你是什么", "你是什么东西",
    "谁啊", "介绍一下你自己", "自我介绍一下",
}
_CAPABILITY = {
    "你能做什么", "你能干什么", "你会什么", "有什么功能", "能做什么", "可以做什么",
    "能帮我什么", "有什么用", "怎么用", "怎么使用", "帮助", "help", "?", "？",
    "你能干啥", "有啥功能", "你会啥", "举个例子", "能干什么",
}

# 出现这些词 = 一定是地理分析任务，绝不能当成闲聊
_TASK_SIGNALS = (
    "坡度", "坡向", "曲率", "路径", "路线", "分类", "统计", "下载", "dem", "DEM",
    "高程", "海拔", "地貌", "地形", "通行", "代价", "面积", "分析", "计算", "规划",
    "走向", "穿越", "越野", "栅格", "哪条路", "怎么走", "成本", "面积", "占比",
)

_PUNCT = re.compile(r"[\s，。！？、,.!?~～…'\"“”‘’：:；;]+")


def _normalize(query: str) -> str:
    """去掉标点空白，转小写 —— 只用于规则匹配，不改动用户原文。"""
    return _PUNCT.sub("", query or "").strip().lower()


def is_chitchat(query: str) -> bool:
    """判断这句话是不是**纯社交寒暄**（打招呼 / 道谢 / 告别）。

    ⚠ 边界收窄说明（2026-09-12 用户反馈后调整）：

    这一层原本还负责「你是谁」「你能做什么」这类元问题。
    实测下来这是错的 —— 用户换个说法（「你有什么功能模块」）就命不中规则，
    于是掉进规划器被当成"越界"拒答，给人的感觉是"只会回答你写死的那几个问题"。

    现在这一层**只处理纯社交寒暄**（这类问题答案固定、且用户希望秒回），
    其余一律交给模型自己判断和回答 —— 泛化能力靠模型，不靠词表。
    """
    raw = (query or "").strip()
    if not raw:
        return False

    q = _normalize(raw)

    # 有任务信号词 → 一定是任务
    for kw in _TASK_SIGNALS:
        if kw.lower() in q:
            return False

    pools = (_GREETINGS, _THANKS, _FAREWELL)

    # 完全相等 —— 最安全的一类
    for pool in pools:
        if q in pool:
            return True

    # 短句且以寒暄词开头 —— 例如「你好呀」「谢谢帮忙」
    if len(q) <= 10:
        for pool in pools:
            for word in pool:
                if q.startswith(word) or q.endswith(word):
                    return True

    return False


def reply_chitchat(query: str) -> str:
    """给出一句人话回复，并顺手告诉用户能怎么用。

    回复里刻意给出真实可执行的例子，而不是"请问有什么可以帮您"这种空话 ——
    这个 Agent 的能力边界很窄（只有 11 个地理工具），用户不知道能问什么就永远用不起来。
    """
    q = _normalize(query)

    if q in _THANKS:
        return "不客气。需要的话可以继续问我，比如「算一下这片区域的坡度」「规划一条翻过山脊的路线」。"

    if q in _FAREWELL:
        return "好的，随时可以再问我。"

    if q in _WHO_ARE_YOU:
        return (
            "我是这个三维地理信息系统里的分析助手，跑在你本机的 Qwen3.5-4B 模型上，"
            "不联网、数据不出本机。我能调用 11 个地理分析工具，把你说的话变成地形图上的结果。"
        )

    if q in _CAPABILITY:
        return (
            "我能做这几类事，直接用中文说就行：\n"
            "· 地形因子 —— 「算一下这一片的坡度」「坡向分布怎么样」\n"
            "· 地貌分类 —— 「判断这里属于什么地貌类型」（默认用 Geomorphons 算法）\n"
            "· 通行性与路径 —— 「哪里好走」「规划一条从 A 到 B 的越野路线」\n"
            "· 分区统计 —— 「多少比例的坡度在 15 度以下」\n"
            "· 数据准备 —— 「下载这一区域的 SRTM 高程数据」\n\n"
            "分析范围默认取你当前的地图视野；也可以直接说地名，比如「贡嘎山」。\n"
            "算完之后结果会渲染成表格和图表，图层可以直接叠加到三维地球上。"
        )

    # 问候：默认分支
    return (
        "你好。我是这个三维地理信息系统的分析助手，可以帮你做坡度坡向分析、"
        "地貌分类、通行性与路径规划、分区统计这些事。\n"
        "范围默认用你当前的地图视野 —— 想看什么直接说就行，比如「分析当前视野的坡度」。\n"
        "不确定我能做什么的话，回一句「你能做什么」就好。"
    )


def try_chitchat(query: str) -> Optional[str]:
    """命中寒暄则返回回复，否则返回 None（交给正常的 Agent 流程）。"""
    if is_chitchat(query):
        return reply_chitchat(query)
    return None
